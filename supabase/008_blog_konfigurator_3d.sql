<h2><span class="idx">08 / FAQ</span>Najczęstsze pytania producentów</h2>

<h3>Czy klienci nie będą się bawić konfiguratorem bez zamiaru zakupu?</h3>
<p>Będą i to jest w porządku — leady zbierasz dopiero na formularzu, więc zabawa nic nie kosztuje. Za to każde wysłane zgłoszenie ma komplet parametrów, więc handlowiec nie traci czasu na zapytania bez treści. Netto: mniej zapytań ogółem, więcej wartościowych.</p>

<h3>Czy konfigurator zadziała na telefonie?</h3>
<p>Musi, bo tam odbywa się większość oglądania. Model 3D w przeglądarce działa na telefonie bez instalowania czegokolwiek — trzeba tylko zoptymalizować geometrię i tekstury, żeby ładował się szybko także na słabszym łączu. To jest część pracy, nie dodatek.</p>

<h3>Czy muszę mieć gotowe modele 3D swoich produktów?</h3>
<p>Nie, ale jeśli masz — projekt jest tańszy i szybszy. Jeżeli nie masz, model przygotowuje się na podstawie dokumentacji technicznej i zdjęć. To osobna pozycja w wycenie, którą podaję po zobaczeniu materiałów.</p>

<h3>Czy konfiguracja może trafiać prosto do naszego systemu?</h3>
<p>Tak, jeśli system udostępnia API lub przyjmuje dane mailem w ustalonym formacie. Sprawdzam dokumentację przed wyceną, żeby nie obiecywać integracji, która okaże się niemożliwa w połowie projektu.</p>

<h3>Czy da się pokazać cenę od razu w konfiguratorze?</h3>
<p>Technicznie tak. Biznesowo — zastanów się, czy chcesz. Część producentów woli, żeby klient dostał cenę od handlowca, bo to otwiera rozmowę i pozwala sprzedać dodatki. Inni pokazują widełki, żeby odsiać osoby z niedopasowanym budżetem. Obie strategie są sensowne, ale to decyzja sprzedażowa, nie techniczna.</p>

